constexpr AiAimParameterSpec number(Page page, const char* path, const char* title,
    double low, double high, double step, int decimals, const char* suffix,
    const char* purpose, const char* adjustment, const char* caution) {
    return {page, path, title, AiAimParameterKind::Number, low, high, step, decimals,
            suffix, purpose, adjustment, caution};
}

constexpr AiAimParameterSpec check(Page page, const char* path, const char* title,
    const char* purpose, const char* adjustment, const char* caution) {
    return {page, path, title, AiAimParameterKind::Check, 0, 1, 1, 0, "",
            purpose, adjustment, caution};
}

